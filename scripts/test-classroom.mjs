#!/usr/bin/env node
/**
 * test-classroom.mjs — contracts for classroom delivery (#224 §5): the offline
 * PWA build step, the generated service worker, the install icons and the
 * recorder's pure helpers. The browser halves (registration, offline reload,
 * update prompt, MediaRecorder) are pinned by e2e.
 *
 *   1. Precache list: every served file except sw.js / maps / dotfiles / notes;
 *      sorted, de-duplicated, separator-agnostic; the version follows URLs *and*
 *      bytes (an unrenamed sim_core.wasm rebuild must bump it).
 *   2. The plugin, run against a scratch out dir, writes a sw.js listing it.
 *   3. The generated worker, executed in a sandbox: install precaches with
 *      `cache: 'reload'` and never skips waiting; navigations with any query get
 *      index.html; precached GET/HEAD are served from cache (HEAD without a
 *      body); everything else is left to the network; activate deletes only
 *      this deploy path's old caches; only `skip-waiting` skips waiting.
 *   4. Install surface: icons are regenerated byte-identical, PNG sizes match
 *      the manifest, manifest paths are relative (Pages / Contabo subpaths),
 *      index.html links it relatively.
 *   5. Recorder helpers: WebM before MP4, audio-capable types only with audio,
 *      file names, burned-in clock, frame fitting, presets, disclaimer.
 *   6. Structure: lazy chunks stay lazy, no query/localStorage reads, no new
 *      runtime dependency, no Workbox.
 *
 * Usage: node scripts/test-classroom.mjs   (exit 1 on failure)
 */
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import * as esbuild from 'esbuild';
import precachePlugin, { buildPrecacheList, renderServiceWorker, isPrecacheable } from './vite-plugin-precache.mjs';
import { renderIcons } from './generate-pwa-icons.mjs';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');

const failures = [];
const ok = [];
function check(label, condition, detail) {
  if (condition) ok.push(label);
  else failures.push(`${label}: ${detail}`);
}

/** What a real build writes (names abbreviated). */
const DIST = [
  ['index.html', '<!doctype html>'],
  ['assets/index-DHsEldEn.js', 'entry'],
  ['assets/index-DP7xyj_G.css', 'css'],
  ['assets/recorder-l2yOdOUm.js', 'lazy'],
  ['assets/plant-worker-q3l9TyWX.js', 'worker'],
  ['assets/index-DHsEldEn.js.map', 'map'],
  ['assets/seg/stand.glb', 'glb'],
  ['assets/seg/LICENSE.md', 'license'],
  ['wasm/sim_core.js', 'glue'],
  ['wasm/sim_core.wasm', 'wasm-v1'],
  ['wasm/README.md', 'readme'],
  ['manifest.webmanifest', '{}'],
  ['icons/icon-192.png', 'png'],
  ['.nojekyll', ''],
  ['sw.js', 'old worker']
].map(([path, bytes]) => ({ path, bytes }));

// ── 1. Precache list ───────────────────────────────────────────────────────
const list = buildPrecacheList(DIST);
{
  for (const must of ['index.html', 'assets/index-DHsEldEn.js', 'assets/index-DP7xyj_G.css', 'assets/recorder-l2yOdOUm.js',
    'assets/plant-worker-q3l9TyWX.js', 'assets/seg/stand.glb', 'wasm/sim_core.js', 'wasm/sim_core.wasm',
    'manifest.webmanifest', 'icons/icon-192.png']) {
    check(`precaches ${must}`, list.urls.includes(must), list.urls.join(', '));
  }
  for (const never of ['sw.js', 'assets/index-DHsEldEn.js.map', '.nojekyll', 'assets/seg/LICENSE.md', 'wasm/README.md']) {
    check(`skips ${never}`, !list.urls.includes(never), list.urls.join(', '));
  }
  check('isPrecacheable skips nested dotfiles', !isPrecacheable('assets/.DS_Store'), 'a dotfile would be cached');
  check('URLs are sorted', list.urls.join('\n') === [...list.urls].sort().join('\n'), list.urls.join(', '));
  check('version is 16 hex digits', /^[0-9a-f]{16}$/.test(list.version), list.version);

  const shuffled = buildPrecacheList([...DIST].reverse());
  check('version ignores file order', shuffled.version === list.version, `${shuffled.version} vs ${list.version}`);
  const windows = buildPrecacheList(DIST.map((f) => ({ ...f, path: f.path.replace(/\//g, '\\') })));
  check('Windows separators give the same URLs and version',
    windows.version === list.version && windows.urls.join() === list.urls.join(), windows.urls.join(', '));
  const dup = buildPrecacheList([...DIST, { path: './index.html', bytes: '<!doctype html>' }]);
  check('duplicates collapse', dup.urls.filter((u) => u === 'index.html').length === 1, dup.urls.join(', '));

  const rebuilt = buildPrecacheList(DIST.map((f) => (f.path === 'wasm/sim_core.wasm' ? { ...f, bytes: 'wasm-v2' } : f)));
  check('a rebuilt sim_core.wasm (same name) bumps the version', rebuilt.version !== list.version, rebuilt.version);
  const added = buildPrecacheList([...DIST, { path: 'assets/new-chunk-abc.js', bytes: 'x' }]);
  check('a new chunk bumps the version', added.version !== list.version, added.version);
  const ignored = buildPrecacheList(DIST.map((f) => (f.path.endsWith('.map') ? { ...f, bytes: 'changed' } : f)));
  check('a changed source map does not', ignored.version === list.version, ignored.version);
}

// ── 2. Plugin against a scratch out dir ────────────────────────────────────
{
  const root = mkdtempSync(join(tmpdir(), 'seg-precache-'));
  try {
    const out = join(root, 'dist');
    for (const f of DIST) {
      mkdirSync(join(out, f.path, '..'), { recursive: true });
      writeFileSync(join(out, f.path), f.bytes);
    }
    const logs = [];
    const plugin = precachePlugin();
    plugin.configResolved({ root: join(root, 'src'), build: { outDir: '../dist' }, logger: { info: (m) => logs.push(m) } });
    plugin.writeBundle.handler.call({});
    const sw = readFileSync(join(out, 'sw.js'), 'utf8');
    check('plugin rewrites sw.js with the built list', list.urls.every((u) => sw.includes(JSON.stringify(u)))
      && sw.includes(JSON.stringify(list.version)), sw.slice(0, 200));
    check('plugin is build-only and runs last', plugin.apply === 'build' && plugin.writeBundle.order === 'post',
      `apply=${plugin.apply} order=${plugin.writeBundle.order}`);
    check('plugin logs a one-line summary', logs.length === 1 && /\d+ URLs/.test(logs[0]), logs.join(' | '));
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
}

// ── 3. The generated worker, in a sandbox ──────────────────────────────────
{
  const src = renderServiceWorker(list);
  check('no placeholder survives rendering', !/__PRECACHE_(VERSION|URLS)__/.test(src), 'placeholder left in sw.js');
  let threw = false;
  try { renderServiceWorker(list, 'const x = 1;'); } catch { threw = true; }
  check('a template without placeholders is an error, not a silent no-op', threw, 'rendered anyway');

  const BASE = 'https://ford442.github.io/power_gen/';
  const handlers = {};
  const stores = new Map([['seg-lab:/power_gen:old', null], ['seg-lab:/power_gen/:0123456789abcdef', new Map()],
    ['seg-lab:/powergen/:0123456789abcdef', new Map()], ['someone-else-v1', new Map()]]);
  const added = [];
  let skipped = 0;
  let claimed = 0;
  const cacheFor = (name) => {
    if (!stores.get(name)) stores.set(name, new Map());
    const store = stores.get(name);
    return {
      addAll: async (reqs) => {
        for (const r of reqs) {
          added.push({ url: r.url, cache: r.cache });
          store.set(r.url, new Response(`body:${r.url}`, { status: 200, headers: { 'content-type': 'x/test', 'x-url': r.url } }));
        }
      },
      // Like the real Cache API: a fresh Response per match.
      match: async (key) => store.get(typeof key === 'string' ? key : key.url)?.clone()
    };
  };
  const sandbox = {
    URL, Request, Response, Set, Map, Promise, console,
    fetch: async (req) => new Response(`network:${req.url ?? req}`),
    caches: {
      open: async (name) => cacheFor(name),
      keys: async () => [...stores.keys()],
      delete: async (name) => stores.delete(name)
    },
    self: {
      location: { href: `${BASE}sw.js` },
      addEventListener: (type, fn) => { handlers[type] = fn; },
      skipWaiting: () => { skipped++; },
      clients: { claim: async () => { claimed++; } }
    }
  };
  vm.runInNewContext(src, sandbox);
  check('worker listens for install / activate / fetch / message',
    ['install', 'activate', 'fetch', 'message'].every((t) => typeof handlers[t] === 'function'), Object.keys(handlers).join(','));

  const waits = [];
  handlers.install({ waitUntil: (p) => waits.push(p) });
  await Promise.all(waits);
  const cacheName = `seg-lab:/power_gen/:${list.version}`;
  check('install precaches every URL into this deploy path\'s versioned cache',
    stores.has(cacheName) && added.length === list.urls.length
      && list.urls.every((u) => added.some((a) => a.url === new URL(u, BASE).href)), `${added.length} vs ${list.urls.length}`);
  check('install bypasses the HTTP cache', added.every((a) => a.cache === 'reload'), JSON.stringify(added[0]));
  check('install never skips waiting (updates wait for the Reload click)', skipped === 0, `skipWaiting ×${skipped}`);
  check('the template never calls skipWaiting outside the message handler',
    (src.match(/self\.skipWaiting\(\)/g) ?? []).length === 1 && /skip-waiting'\) self\.skipWaiting\(\)/.test(src),
    'an unconditional skipWaiting() crept in');

  /** Dispatch a fetch; resolve the response, or null when left to the network. */
  const fetchEvent = async (url, { mode = 'no-cors', method = 'GET' } = {}) => {
    let responded = null;
    handlers.fetch({ request: { url, mode, method }, respondWith: (p) => { responded = p; } });
    return responded ? await responded : null;
  };
  const nav = await fetchEvent(`${BASE}?renderer=webgl2#lab=abc`, { mode: 'navigate' });
  check('a navigation with a query gets the cached index.html',
    nav && (await nav.text()) === `body:${BASE}index.html`, String(nav));
  const nav2 = await fetchEvent(`${BASE}index.html?wasmPhysics=1`, { mode: 'navigate' });
  check('…so does /index.html?…', nav2 && (await nav2.text()) === `body:${BASE}index.html`, String(nav2));
  check('a navigation elsewhere in scope goes to the network',
    (await fetchEvent(`${BASE}docs/CLASSROOM.md`, { mode: 'navigate' })) === null, 'served from cache');
  const wasm = await fetchEvent(`${BASE}wasm/sim_core.wasm`);
  check('a precached asset is served from cache', wasm && (await wasm.text()) === `body:${BASE}wasm/sim_core.wasm`, String(wasm));
  const head = await fetchEvent(`${BASE}wasm/sim_core.wasm`, { method: 'HEAD' });
  check('a HEAD probe gets cached status + headers, no body',
    head && head.status === 200 && head.body === null && head.headers.get('x-url') === `${BASE}wasm/sim_core.wasm`, String(head));
  check('a non-precached URL is left to the network', (await fetchEvent(`${BASE}favicon.ico`)) === null, 'intercepted');
  check('POST is never intercepted', (await fetchEvent(`${BASE}wasm/sim_core.wasm`, { method: 'POST' })) === null, 'intercepted');
  check('another app on the origin is never intercepted',
    (await fetchEvent('https://ford442.github.io/other_app/', { mode: 'navigate' })) === null, 'intercepted');

  const activations = [];
  handlers.activate({ waitUntil: (p) => activations.push(p) });
  await Promise.all(activations);
  check('activate deletes this deploy path\'s old caches',
    !stores.has('seg-lab:/power_gen/:0123456789abcdef') && stores.has(cacheName), [...stores.keys()].join(', '));
  check('…and leaves other deploy paths and other apps alone',
    stores.has('seg-lab:/powergen/:0123456789abcdef') && stores.has('someone-else-v1'), [...stores.keys()].join(', '));
  check('activate claims the open page', claimed === 1, `claim ×${claimed}`);

  handlers.message({ data: { type: 'hello' } });
  handlers.message({ data: null });
  check('other messages do not skip waiting', skipped === 0, `skipWaiting ×${skipped}`);
  handlers.message({ data: { type: 'skip-waiting' } });
  check('the Reload click\'s skip-waiting does', skipped === 1, `skipWaiting ×${skipped}`);
}

// ── 4. Install surface: icons, manifest, link ──────────────────────────────
{
  for (const [rel, bytes] of Object.entries(renderIcons())) {
    const full = join(ROOT, rel);
    check(`${rel} is committed and up to date`, existsSync(full) && readFileSync(full).equals(bytes),
      'run npm run generate:pwa-icons');
  }
  const manifest = JSON.parse(read('src/public/manifest.webmanifest'));
  check('manifest start_url / scope / id are relative to the deploy path',
    manifest.start_url === './' && manifest.scope === './' && manifest.id === './', JSON.stringify(manifest.start_url));
  check('manifest is installable-shaped (name, short_name, standalone)',
    !!manifest.name && !!manifest.short_name && manifest.display === 'standalone', JSON.stringify(manifest));
  for (const icon of manifest.icons) {
    const full = join(ROOT, 'src/public', icon.src);
    check(`manifest icon ${icon.src} (${icon.purpose}) exists and is relative`,
      existsSync(full) && !icon.src.startsWith('/'), icon.src);
    if (icon.type === 'image/png') {
      const png = readFileSync(full);
      const w = png.readUInt32BE(16);
      const h = png.readUInt32BE(20);
      check(`${icon.src} really is ${icon.sizes}`, `${w}x${h}` === icon.sizes, `${w}x${h}`);
    }
  }
  const sizes = manifest.icons.filter((i) => i.type === 'image/png').map((i) => i.sizes);
  check('PNG icons at 192 and 512 (Chrome install criteria)', sizes.includes('192x192') && sizes.includes('512x512'),
    sizes.join(', '));
  check('a maskable icon is declared', manifest.icons.some((i) => i.purpose === 'maskable'), 'no maskable icon');
  const html = read('src/index.html');
  check('index.html links the manifest relatively', /<link rel="manifest" href="manifest\.webmanifest">/.test(html),
    'manifest link missing or absolute');
  const theme = html.match(/<meta name="theme-color" content="([^"]+)">/)?.[1];
  check('theme-color meta matches the manifest', theme === manifest.theme_color, `${theme} vs ${manifest.theme_color}`);
}

// ── 5. Recorder helpers ────────────────────────────────────────────────────
{
  const hubStub = {
    name: 'hub-stub',
    setup(build) {
      build.onResolve({ filter: /telemetry-hub$/ }, () => ({ path: 'hub', namespace: 'stub' }));
      build.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
        contents: 'export const telemetryHub = { getSimTimeS: () => 0 };', loader: 'js'
      }));
    }
  };
  const built = await esbuild.build({
    entryPoints: [join(ROOT, 'src/classroom/recorder.ts')],
    bundle: true, format: 'esm', platform: 'neutral', write: false, logLevel: 'silent', plugins: [hubStub]
  });
  const r = await import(`data:text/javascript,${encodeURIComponent(built.outputFiles[0].text)}`);

  const supports = (...types) => (t) => types.includes(t);
  const chrome = supports('video/webm;codecs=vp9,opus', 'video/webm;codecs=vp9', 'video/webm;codecs=vp8,opus',
    'video/webm;codecs=vp8', 'video/webm');
  const safari = supports('video/mp4;codecs=avc1,mp4a.40.2', 'video/mp4;codecs=avc1', 'video/mp4');
  const both = (t) => chrome(t) || safari(t);
  check('Chrome-like: VP9 + Opus with audio', r.pickRecorderMimeType(chrome, true) === 'video/webm;codecs=vp9,opus',
    r.pickRecorderMimeType(chrome, true));
  check('Chrome-like: VP9 without audio', r.pickRecorderMimeType(chrome, false) === 'video/webm;codecs=vp9',
    r.pickRecorderMimeType(chrome, false));
  check('Safari-like: MP4 H.264 + AAC with audio', r.pickRecorderMimeType(safari, true) === 'video/mp4;codecs=avc1,mp4a.40.2',
    r.pickRecorderMimeType(safari, true));
  check('WebM wins when both are supported', r.pickRecorderMimeType(both, true).startsWith('video/webm'),
    r.pickRecorderMimeType(both, true));
  check('nothing supported → null', r.pickRecorderMimeType(() => false, false) === null, 'returned a type');
  check('a throwing probe counts as unsupported',
    r.pickRecorderMimeType((t) => { if (t.includes('vp9')) throw new Error('x'); return t === 'video/webm'; }, false) === 'video/webm',
    'a throw escaped');
  const videoOnlyCodecs = supports('video/webm;codecs=vp9', 'video/mp4;codecs=avc1');
  check('with audio, never a video-only codec string', r.pickRecorderMimeType(videoOnlyCodecs, true) === null,
    r.pickRecorderMimeType(videoOnlyCodecs, true));

  const when = new Date(2026, 9, 18, 10, 44, 3);
  check('file name: seg-lab-<local timestamp>.webm',
    r.recordingFileName(when, 'video/webm;codecs=vp9') === 'seg-lab-2026-10-18T10-44-03.webm', r.recordingFileName(when, 'video/webm'));
  check('file name: .mp4 for MP4', r.recordingFileName(when, 'video/mp4;codecs=avc1').endsWith('.mp4'),
    r.recordingFileName(when, 'video/mp4'));
  check('burned-in clock: sim seconds + wall time',
    r.formatRecordingClock(12.345, when) === 'sim t = 12.35 s · 2026-10-18 10:44:03', r.formatRecordingClock(12.345, when));
  check('burned-in clock survives NaN', r.formatRecordingClock(Number.NaN, when).startsWith('sim t = — s'),
    r.formatRecordingClock(Number.NaN, when));
  const big = r.fitRecordingSize(3840, 2160);
  check('a 4K canvas is encoded at 1920×1080', big.width === 1920 && big.height === 1080, JSON.stringify(big));
  const odd = r.fitRecordingSize(1171, 659);
  check('frame dimensions are even', odd.width % 2 === 0 && odd.height % 2 === 0, JSON.stringify(odd));
  const none = r.fitRecordingSize(0, 0);
  check('a zero-sized canvas falls back to 1280×720', none.width === 1280 && none.height === 720, JSON.stringify(none));
  check('disclaimer text', r.RECORDING_DISCLAIMER === 'Simulated — not metrology', r.RECORDING_DISCLAIMER);
  check('presets are 10 / 30 / 60 s', r.RECORD_PRESETS_S.join() === '10,30,60', r.RECORD_PRESETS_S.join());
  const controlPresets = read('src/classroom/record-control.ts').match(/const PRESETS_S = \[([^\]]+)\]/)?.[1].replace(/\s/g, '');
  check('the Record control offers the same presets', controlPresets === r.RECORD_PRESETS_S.join(), String(controlPresets));
  check('single-flight guard: isRecording() exists and starts false', typeof r.isRecording === 'function' && r.isRecording() === false,
    'isRecording missing');
}

// ── 6. Structure ───────────────────────────────────────────────────────────
{
  const files = ['install.ts', 'pwa-register.ts', 'record-control.ts', 'recorder.ts', 'sw-template.js'];
  for (const f of files) {
    const src = read(`src/classroom/${f}`);
    check(`${f} reads no query string or localStorage (LabConfig owns that)`,
      !/location\.search|URLSearchParams|localStorage/.test(src), 'found a direct read');
  }
  const main = read('src/main.ts');
  check('main.ts loads the classroom chunk lazily', /import\('\.\/classroom\/install'\)/.test(main)
    && !/^import .*classroom/m.test(main), 'static classroom import in main.ts');
  const offenders = ['src/main.ts', 'src/classroom/install.ts', 'src/classroom/record-control.ts']
    .filter((rel) => /^import [^;]*'\.\/recorder'/m.test(read(rel)));
  check('the recorder is only ever imported dynamically', offenders.length === 0, offenders.join(', '));
  check('install.ts registers ./sw.js relative to the base',
    /register\(`\$\{import\.meta\.env\.BASE_URL\}sw\.js`\)/.test(read('src/classroom/pwa-register.ts')), 'register path changed');
  check('vite.config.js runs the precache plugin', /precache\(\)/.test(read('vite.config.js')), 'plugin not registered');
  const pkg = JSON.parse(read('package.json'));
  check('no new runtime dependency', Object.keys(pkg.dependencies ?? {}).join() === 'ktx-parse',
    Object.keys(pkg.dependencies ?? {}).join());
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  check('no Workbox / vite-plugin-pwa', !Object.keys(deps).some((d) => /workbox|vite-plugin-pwa/.test(d)),
    Object.keys(deps).join());
}

for (const line of ok) console.log(`  ok: ${line}`);
if (failures.length) {
  for (const line of failures) console.error(`  FAIL: ${line}`);
  console.error(`[classroom] ${failures.length} failure(s)`);
  process.exit(1);
}
console.log(`[classroom] ${ok.length} checks passed`);
