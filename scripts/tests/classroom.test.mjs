import { join } from 'node:path';
import { after, before, describe, it } from 'node:test';
import vm from 'node:vm';
import { renderIcons } from '../generate-pwa-icons.mjs';
import { ROOT, bundleTs } from '../test-harness.mjs';
import precachePlugin, { buildPrecacheList, isPrecacheable, renderServiceWorker } from '../vite-plugin-precache.mjs';

const read = (rel) => readFileSync(join(ROOT, rel), 'utf8');

/** What a real build writes (names abbreviated). */
const DIST = [
  ['index.html', '<!doctype html>'],
  ['assets/index-DHsEldEn.js', 'entry'],
  ['assets/index-DP7xyj_G.css', 'css'],
  ['assets/recorder-l2yOdOUm.js', 'lazy'],
  ['assets/plant-worker-q3l9TyWX.js', 'worker'],
  ['assets/index-DHsEldEn.js.map', 'map'],
  ['assets/seg/stand.glb', 'glb'],
  ['assets/seg/LICENSE.md', 'license'],
  ['wasm/sim_core.js', 'glue'],
  ['wasm/sim_core.wasm', 'wasm-v1'],
  ['wasm/README.md', 'readme'],
  ['manifest.webmanifest', '{}'],
  ['icons/icon-192.png', 'png'],
  ['.nojekyll', ''],
  ['sw.js', 'old worker']
].map(([path, bytes]) => ({ path, bytes }));

const list = buildPrecacheList(DIST);

describe('1. precache list', () => {
  for (const must of ['index.html', 'assets/index-DHsEldEn.js', 'assets/index-DP7xyj_G.css', 'assets/recorder-l2yOdOUm.js',
    'assets/plant-worker-q3l9TyWX.js', 'assets/seg/stand.glb', 'wasm/sim_core.js', 'wasm/sim_core.wasm',
    'manifest.webmanifest', 'icons/icon-192.png']) {
    it(`precaches ${must}`, () => {
      assert.ok(list.urls.includes(must), list.urls.join(', '));
    });
  }
  for (const never of ['sw.js', 'assets/index-DHsEldEn.js.map', '.nojekyll', 'assets/seg/LICENSE.md', 'wasm/README.md']) {
    it(`skips ${never}`, () => {
      assert.ok(!list.urls.includes(never), list.urls.join(', '));
    });
  }
  it('isPrecacheable skips nested dotfiles', () => {
    assert.ok(!isPrecacheable('assets/.DS_Store'), 'a dotfile would be cached');
  });
  it('URLs are sorted', () => {
    assert.ok(list.urls.join('\n') === [...list.urls].sort().join('\n'), list.urls.join(', '));
  });
  it('version is 16 hex digits', () => {
    assert.match(list.version, /^[0-9a-f]{16}$/);
  });
  it('version ignores file order', () => {
    const shuffled = buildPrecacheList([...DIST].reverse());
    assert.ok(shuffled.version === list.version, `${shuffled.version} vs ${list.version}`);
  });
  it('Windows separators give the same URLs and version', () => {
    const windows = buildPrecacheList(DIST.map((f) => ({ ...f, path: f.path.replace(/\//g, '\\') })));
    assert.ok(windows.version === list.version && windows.urls.join() === list.urls.join(), windows.urls.join(', '));
  });
  it('duplicates collapse', () => {
    const dup = buildPrecacheList([...DIST, { path: './index.html', bytes: '<!doctype html>' }]);
    assert.ok(dup.urls.filter((u) => u === 'index.html').length === 1, dup.urls.join(', '));
  });
  it('a rebuilt sim_core.wasm (same name) bumps the version', () => {
    const rebuilt = buildPrecacheList(DIST.map((f) => (f.path === 'wasm/sim_core.wasm' ? { ...f, bytes: 'wasm-v2' } : f)));
    assert.ok(rebuilt.version !== list.version, rebuilt.version);
  });
  it('a new chunk bumps the version', () => {
    const added = buildPrecacheList([...DIST, { path: 'assets/new-chunk-abc.js', bytes: 'x' }]);
    assert.ok(added.version !== list.version, added.version);
  });
  it('a changed source map does not', () => {
    const ignored = buildPrecacheList(DIST.map((f) => (f.path.endsWith('.map') ? { ...f, bytes: 'changed' } : f)));
    assert.ok(ignored.version === list.version, ignored.version);
  });
});

describe('2. plugin against a scratch out dir', () => {
  let root, sw, plugin;
  const logs = [];
  before(() => {
    root = mkdtempSync(join(tmpdir(), 'seg-precache-'));
    const out = join(root, 'dist');
    for (const f of DIST) {
      mkdirSync(join(out, f.path, '..'), { recursive: true });
      writeFileSync(join(out, f.path), f.bytes);
    }
    plugin = precachePlugin();
    plugin.configResolved({ root: join(root, 'src'), build: { outDir: '../dist' }, logger: { info: (m) => logs.push(m) } });
    plugin.writeBundle.handler.call({});
    sw = readFileSync(join(out, 'sw.js'), 'utf8');
  });
  after(() => rmSync(root, { recursive: true, force: true }));

  it('plugin rewrites sw.js with the built list', () => {
    assert.ok(list.urls.every((u) => sw.includes(JSON.stringify(u))) && sw.includes(JSON.stringify(list.version)), sw.slice(0, 200));
  });
  it('plugin is build-only and runs last', () => {
    assert.ok(plugin.apply === 'build' && plugin.writeBundle.order === 'post', `apply=${plugin.apply} order=${plugin.writeBundle.order}`);
  });
  it('plugin logs a one-line summary', () => {
    assert.ok(logs.length === 1 && /\d+ URLs/.test(logs[0]), logs.join(' | '));
  });
});

describe('3. the generated worker, in a sandbox', () => {
  const src = renderServiceWorker(list);
  it('no placeholder survives rendering', () => {
    assert.ok(!/__PRECACHE_(VERSION|URLS)__/.test(src), 'placeholder left in sw.js');
  });
  it('a template without placeholders is an error, not a silent no-op', () => {
    assert.throws(() => renderServiceWorker(list, 'const x = 1;'), undefined, 'rendered anyway');
  });

  // The steps below share one worker instance and its cache stores; they run in order.
  const BASE = 'https://ford442.github.io/power_gen/';
  const handlers = {};
  const stores = new Map([['seg-lab:/power_gen:old', null], ['seg-lab:/power_gen/:0123456789abcdef', new Map()],
    ['seg-lab:/powergen/:0123456789abcdef', new Map()], ['someone-else-v1', new Map()]]);
  const added = [];
  let skipped = 0;
  let claimed = 0;
  const cacheName = `seg-lab:/power_gen/:${list.version}`;
  const cacheFor = (name) => {
    if (!stores.get(name)) stores.set(name, new Map());
    const store = stores.get(name);
    return {
      addAll: async (reqs) => {
        for (const r of reqs) {
          added.push({ url: r.url, cache: r.cache });
          store.set(r.url, new Response(`body:${r.url}`, { status: 200, headers: { 'content-type': 'x/test', 'x-url': r.url } }));
        }
      },
      // Like the real Cache API: a fresh Response per match.
      match: async (key) => store.get(typeof key === 'string' ? key : key.url)?.clone()
    };
  };
  /** Dispatch a fetch; resolve the response, or null when left to the network. */
  const fetchEvent = async (url, { mode = 'no-cors', method = 'GET' } = {}) => {
    let responded = null;
    handlers.fetch({ request: { url, mode, method }, respondWith: (p) => { responded = p; } });
    return responded ? await responded : null;
  };

  before(() => {
    const sandbox = {
      URL, Request, Response, Set, Map, Promise, console,
      fetch: async (req) => new Response(`network:${req.url ?? req}`),
      caches: {
        open: async (name) => cacheFor(name),
        keys: async () => [...stores.keys()],
        delete: async (name) => stores.delete(name)
      },
      self: {
        location: { href: `${BASE}sw.js` },
        addEventListener: (type, fn) => { handlers[type] = fn; },
        skipWaiting: () => { skipped++; },
        clients: { claim: async () => { claimed++; } }
      }
    };
    vm.runInNewContext(src, sandbox);
  });

  it('worker listens for install / activate / fetch / message', () => {
    assert.ok(['install', 'activate', 'fetch', 'message'].every((t) => typeof handlers[t] === 'function'), Object.keys(handlers).join(','));
  });

  it('install precaches every URL with cache: reload and never skips waiting', async () => {
    const waits = [];
    handlers.install({ waitUntil: (p) => waits.push(p) });
    await Promise.all(waits);
    assert.ok(stores.has(cacheName) && added.length === list.urls.length
      && list.urls.every((u) => added.some((a) => a.url === new URL(u, BASE).href)),
    `install precaches every URL into this deploy path's versioned cache — ${added.length} vs ${list.urls.length}`);
    assert.ok(added.every((a) => a.cache === 'reload'), `install bypasses the HTTP cache — ${JSON.stringify(added[0])}`);
    assert.ok(skipped === 0, `install never skips waiting (updates wait for the Reload click) — skipWaiting ×${skipped}`);
  });
  it('the template never calls skipWaiting outside the message handler', () => {
    assert.ok((src.match(/self\.skipWaiting\(\)/g) ?? []).length === 1 && /skip-waiting'\) self\.skipWaiting\(\)/.test(src),
      'an unconditional skipWaiting() crept in');
  });

  it('a navigation with a query gets the cached index.html', async () => {
    const nav = await fetchEvent(`${BASE}?renderer=webgl2#lab=abc`, { mode: 'navigate' });
    assert.ok(nav && (await nav.text()) === `body:${BASE}index.html`, String(nav));
  });
  it('…so does /index.html?…', async () => {
    const nav2 = await fetchEvent(`${BASE}index.html?wasmPhysics=1`, { mode: 'navigate' });
    assert.ok(nav2 && (await nav2.text()) === `body:${BASE}index.html`, String(nav2));
  });
  it('a navigation elsewhere in scope goes to the network', async () => {
    assert.ok((await fetchEvent(`${BASE}docs/CLASSROOM.md`, { mode: 'navigate' })) === null, 'served from cache');
  });
  it('a precached asset is served from cache', async () => {
    const wasm = await fetchEvent(`${BASE}wasm/sim_core.wasm`);
    assert.ok(wasm && (await wasm.text()) === `body:${BASE}wasm/sim_core.wasm`, String(wasm));
  });
  it('a HEAD probe gets cached status + headers, no body', async () => {
    const head = await fetchEvent(`${BASE}wasm/sim_core.wasm`, { method: 'HEAD' });
    assert.ok(head && head.status === 200 && head.body === null && head.headers.get('x-url') === `${BASE}wasm/sim_core.wasm`, String(head));
  });
  it('a non-precached URL is left to the network', async () => {
    assert.ok((await fetchEvent(`${BASE}favicon.ico`)) === null, 'intercepted');
  });
  it('POST is never intercepted', async () => {
    assert.ok((await fetchEvent(`${BASE}wasm/sim_core.wasm`, { method: 'POST' })) === null, 'intercepted');
  });
  it('another app on the origin is never intercepted', async () => {
    assert.ok((await fetchEvent('https://ford442.github.io/other_app/', { mode: 'navigate' })) === null, 'intercepted');
  });

  it('activate deletes only this deploy path\'s old caches and claims the page', async () => {
    const activations = [];
    handlers.activate({ waitUntil: (p) => activations.push(p) });
    await Promise.all(activations);
    assert.ok(!stores.has('seg-lab:/power_gen/:0123456789abcdef') && stores.has(cacheName),
      `activate deletes this deploy path's old caches — ${[...stores.keys()].join(', ')}`);
    assert.ok(stores.has('seg-lab:/powergen/:0123456789abcdef') && stores.has('someone-else-v1'),
      `…and leaves other deploy paths and other apps alone — ${[...stores.keys()].join(', ')}`);
    assert.ok(claimed === 1, `activate claims the open page — claim ×${claimed}`);
  });

  it('only the Reload click\'s skip-waiting message skips waiting', () => {
    handlers.message({ data: { type: 'hello' } });
    handlers.message({ data: null });
    assert.ok(skipped === 0, `other messages do not skip waiting — skipWaiting ×${skipped}`);
    handlers.message({ data: { type: 'skip-waiting' } });
    assert.ok(skipped === 1, `the Reload click's skip-waiting does — skipWaiting ×${skipped}`);
  });
});

describe('4. install surface: icons, manifest, link', () => {
  for (const [rel, bytes] of Object.entries(renderIcons())) {
    it(`${rel} is committed and up to date`, () => {
      const full = join(ROOT, rel);
      assert.ok(existsSync(full) && readFileSync(full).equals(bytes), 'run npm run generate:pwa-icons');
    });
  }
  const manifest = JSON.parse(read('src/public/manifest.webmanifest'));
  it('manifest start_url / scope / id are relative to the deploy path', () => {
    assert.ok(manifest.start_url === './' && manifest.scope === './' && manifest.id === './', JSON.stringify(manifest.start_url));
  });
  it('manifest is installable-shaped (name, short_name, standalone)', () => {
    assert.ok(!!manifest.name && !!manifest.short_name && manifest.display === 'standalone', JSON.stringify(manifest));
  });
  for (const icon of manifest.icons) {
    it(`manifest icon ${icon.src} (${icon.purpose}) exists and is relative${icon.type === 'image/png' ? `, really is ${icon.sizes}` : ''}`, () => {
      const full = join(ROOT, 'src/public', icon.src);
      assert.ok(existsSync(full) && !icon.src.startsWith('/'), icon.src);
      if (icon.type === 'image/png') {
        const png = readFileSync(full);
        const w = png.readUInt32BE(16);
        const h = png.readUInt32BE(20);
        assert.ok(`${w}x${h}` === icon.sizes, `${icon.src} really is ${icon.sizes}: ${w}x${h}`);
      }
    });
  }
  it('PNG icons at 192 and 512 (Chrome install criteria)', () => {
    const sizes = manifest.icons.filter((i) => i.type === 'image/png').map((i) => i.sizes);
    assert.ok(sizes.includes('192x192') && sizes.includes('512x512'), sizes.join(', '));
  });
  it('a maskable icon is declared', () => {
    assert.ok(manifest.icons.some((i) => i.purpose === 'maskable'), 'no maskable icon');
  });
  const html = read('src/index.html');
  it('index.html links the manifest relatively', () => {
    assert.ok(/<link rel="manifest" href="manifest\.webmanifest">/.test(html), 'manifest link missing or absolute');
  });
  it('theme-color meta matches the manifest', () => {
    const theme = html.match(/<meta name="theme-color" content="([^"]+)">/)?.[1];
    assert.ok(theme === manifest.theme_color, `${theme} vs ${manifest.theme_color}`);
  });
});

describe('5. recorder helpers', () => {
  const hubStub = {
    name: 'hub-stub',
    setup(build) {
      build.onResolve({ filter: /telemetry-hub$/ }, () => ({ path: 'hub', namespace: 'stub' }));
      build.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
        contents: 'export const telemetryHub = { getSimTimeS: () => 0 };', loader: 'js'
      }));
    }
  };
  let r;
  before(async () => {
    r = await bundleTs('src/classroom/recorder.ts', { plugins: [hubStub] });
  });

  const supports = (...types) => (t) => types.includes(t);
  const chrome = supports('video/webm;codecs=vp9,opus', 'video/webm;codecs=vp9', 'video/webm;codecs=vp8,opus',
    'video/webm;codecs=vp8', 'video/webm');
  const safari = supports('video/mp4;codecs=avc1,mp4a.40.2', 'video/mp4;codecs=avc1', 'video/mp4');
  const both = (t) => chrome(t) || safari(t);

  it('Chrome-like: VP9 + Opus with audio', () => {
    assert.ok(r.pickRecorderMimeType(chrome, true) === 'video/webm;codecs=vp9,opus', r.pickRecorderMimeType(chrome, true));
  });
  it('Chrome-like: VP9 without audio', () => {
    assert.ok(r.pickRecorderMimeType(chrome, false) === 'video/webm;codecs=vp9', r.pickRecorderMimeType(chrome, false));
  });
  it('Safari-like: MP4 H.264 + AAC with audio', () => {
    assert.ok(r.pickRecorderMimeType(safari, true) === 'video/mp4;codecs=avc1,mp4a.40.2', r.pickRecorderMimeType(safari, true));
  });
  it('WebM wins when both are supported', () => {
    assert.ok(r.pickRecorderMimeType(both, true).startsWith('video/webm'), r.pickRecorderMimeType(both, true));
  });
  it('nothing supported → null', () => {
    assert.ok(r.pickRecorderMimeType(() => false, false) === null, 'returned a type');
  });
  it('a throwing probe counts as unsupported', () => {
    assert.ok(r.pickRecorderMimeType((t) => { if (t.includes('vp9')) throw new Error('x'); return t === 'video/webm'; }, false) === 'video/webm',
      'a throw escaped');
  });
  it('with audio, never a video-only codec string', () => {
    const videoOnlyCodecs = supports('video/webm;codecs=vp9', 'video/mp4;codecs=avc1');
    assert.ok(r.pickRecorderMimeType(videoOnlyCodecs, true) === null, String(r.pickRecorderMimeType(videoOnlyCodecs, true)));
  });

  const when = new Date(2026, 9, 18, 10, 44, 3);
  it('file name: seg-lab-<local timestamp>.webm', () => {
    assert.ok(r.recordingFileName(when, 'video/webm;codecs=vp9') === 'seg-lab-2026-10-18T10-44-03.webm', r.recordingFileName(when, 'video/webm'));
  });
  it('file name: .mp4 for MP4', () => {
    assert.ok(r.recordingFileName(when, 'video/mp4;codecs=avc1').endsWith('.mp4'), r.recordingFileName(when, 'video/mp4'));
  });
  it('burned-in clock: sim seconds + wall time', () => {
    assert.ok(r.formatRecordingClock(12.345, when) === 'sim t = 12.35 s · 2026-10-18 10:44:03', r.formatRecordingClock(12.345, when));
  });
  it('burned-in clock survives NaN', () => {
    assert.ok(r.formatRecordingClock(Number.NaN, when).startsWith('sim t = — s'), r.formatRecordingClock(Number.NaN, when));
  });
  it('a 4K canvas is encoded at 1920×1080', () => {
    const big = r.fitRecordingSize(3840, 2160);
    assert.ok(big.width === 1920 && big.height === 1080, JSON.stringify(big));
  });
  it('frame dimensions are even', () => {
    const odd = r.fitRecordingSize(1171, 659);
    assert.ok(odd.width % 2 === 0 && odd.height % 2 === 0, JSON.stringify(odd));
  });
  it('a zero-sized canvas falls back to 1280×720', () => {
    const none = r.fitRecordingSize(0, 0);
    assert.ok(none.width === 1280 && none.height === 720, JSON.stringify(none));
  });
  it('disclaimer text', () => {
    assert.ok(r.RECORDING_DISCLAIMER === 'Simulated — not metrology', r.RECORDING_DISCLAIMER);
  });
  it('presets are 10 / 30 / 60 s', () => {
    assert.ok(r.RECORD_PRESETS_S.join() === '10,30,60', r.RECORD_PRESETS_S.join());
  });
  it('the Record control offers the same presets', () => {
    const controlPresets = read('src/classroom/record-control.ts').match(/const PRESETS_S = \[([^\]]+)\]/)?.[1].replace(/\s/g, '');
    assert.ok(controlPresets === r.RECORD_PRESETS_S.join(), String(controlPresets));
  });
  it('single-flight guard: isRecording() exists and starts false', () => {
    assert.ok(typeof r.isRecording === 'function' && r.isRecording() === false, 'isRecording missing');
  });
});

describe('6. structure', () => {
  for (const f of ['install.ts', 'pwa-register.ts', 'record-control.ts', 'recorder.ts', 'sw-template.js']) {
    it(`${f} reads no query string or localStorage (LabConfig owns that)`, () => {
      assert.ok(!/location\.search|URLSearchParams|localStorage/.test(read(`src/classroom/${f}`)), 'found a direct read');
    });
  }
  it('main.ts loads the classroom chunk lazily', () => {
    const main = read('src/main.ts');
    assert.ok(/import\('\.\/classroom\/install'\)/.test(main) && !/^import .*classroom/m.test(main), 'static classroom import in main.ts');
  });
  it('the recorder is only ever imported dynamically', () => {
    const offenders = ['src/main.ts', 'src/classroom/install.ts', 'src/classroom/record-control.ts']
      .filter((rel) => /^import [^;]*'\.\/recorder'/m.test(read(rel)));
    assert.ok(offenders.length === 0, offenders.join(', '));
  });
  it('install.ts registers ./sw.js relative to the base', () => {
    assert.ok(/register\(`\$\{import\.meta\.env\.BASE_URL\}sw\.js`\)/.test(read('src/classroom/pwa-register.ts')), 'register path changed');
  });
  it('vite.config.js runs the precache plugin', () => {
    assert.ok(/precache\(\)/.test(read('vite.config.js')), 'plugin not registered');
  });
  const pkg = JSON.parse(read('package.json'));
  it('no new runtime dependency', () => {
    // The lab's runtime deps (KTX2 props, the share-link QR, the analysis
    // panel's uPlot) — the classroom code adds none.
    const knownDeps = ['ktx-parse', 'qrcode-generator', 'uplot'];
    assert.ok(Object.keys(pkg.dependencies ?? {}).every((d) => knownDeps.includes(d)), Object.keys(pkg.dependencies ?? {}).join());
  });
  it('no Workbox / vite-plugin-pwa', () => {
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    assert.ok(!Object.keys(deps).some((d) => /workbox|vite-plugin-pwa/.test(d)), Object.keys(deps).join());
  });
});
