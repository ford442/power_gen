/**
 * classroom — contracts for classroom delivery (#224 §5): the offline PWA build
 * step, the generated service worker, the install icons and the recorder's pure
 * helpers. The browser halves (registration, offline reload, update prompt,
 * MediaRecorder) are pinned by e2e.
 *
 *   1. Precache list: every served file except sw.js / maps / dotfiles / notes;
 *      sorted, de-duplicated, separator-agnostic; the version follows URLs *and*
 *      bytes (an unrenamed sim_core.wasm rebuild must bump it).
 *   2. The plugin, run against a scratch out dir, writes a sw.js listing it.
 *   3. The generated worker, executed in a sandbox: install precaches with
 *      `cache: 'reload'` and never skips waiting; navigations with any query get
 *      index.html; precached GET/HEAD are served from cache (HEAD without a
 *      body); everything else is left to the network; activate deletes only
 *      this deploy path's old caches; only `skip-waiting` skips waiting.
 *   4. Install surface: icons are regenerated byte-identical, PNG sizes match
 *      the manifest, manifest paths are relative (Pages / Contabo subpaths),
 *      index.html links it relatively.
 *   5. Recorder helpers: WebM before MP4, audio-capable types only with audio,
 *      file names, burned-in clock, frame fitting, presets, disclaimer.
 *   6. Structure: lazy chunks stay lazy, no query/localStorage reads, no new
 *      runtime dependency, no Workbox.
 *
 * Usage: npm run test:classroom   (node --test scripts/tests/classroom.test.mjs)
 */
import assert from 'node:assert/strict';
