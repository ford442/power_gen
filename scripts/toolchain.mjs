#!/usr/bin/env node
/**
 * toolchain.mjs — config/toolchain.json is the one pin file for the tools the
 * build and CI run (#258 §6): emsdk, naga, node, playwright.
 *
 *   node scripts/toolchain.mjs emsdk            print one pin (shell / CI steps)
 *   node scripts/toolchain.mjs --github-output  write every pin as key=value to
 *                                               $GITHUB_OUTPUT (stdout without it)
 *   node scripts/toolchain.mjs --write          codegen:toolchain — regenerate the
 *                                               mirrors (.nvmrc, cpp/README.md table)
 *   node scripts/toolchain.mjs --check          check:toolchain — mirrors current,
 *                                               no hard-coded version elsewhere
 *
 * Mirrors exist only where a tool dictates the location:
 *   .nvmrc                       nvm / fnm / actions/setup-node read it
 *   package.json + lockfile      npm installs @playwright/test from there; the
 *                                browser build (and so the image baselines)
 *                                follows that exact version
 * Everything else reads the pin through this script.
 */
import { execFileSync } from 'node:child_process';
import { appendFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PIN_FILE = 'config/toolchain.json';
const TOOLS = ['emsdk', 'naga', 'node', 'playwright'];

/** The pins: `{ emsdk, naga, node, playwright }`, all strings. */
export function toolchain(root = ROOT) {
  const raw = JSON.parse(readFileSync(join(root, PIN_FILE), 'utf8'));
  const pins = {};
  for (const tool of TOOLS) {
    if (typeof raw[tool] !== 'string' || !raw[tool]) throw new Error(`${PIN_FILE}: "${tool}" must be a version string`);
    pins[tool] = raw[tool];
  }
  const extra = Object.keys(raw).filter((k) => !k.startsWith('$') && !TOOLS.includes(k));
  if (extra.length) throw new Error(`${PIN_FILE}: unknown key(s) ${extra.join(', ')} — add them to scripts/toolchain.mjs`);
  return pins;
}

// ── Generated mirrors ──────────────────────────────────────────────────────
const README = 'cpp/README.md';
const BEGIN = '<!-- toolchain:begin (generated by `npm run codegen:toolchain` from config/toolchain.json) -->';
const END = '<!-- toolchain:end -->';

function readmeTable(pins) {
  return [
    BEGIN,
    '| Tool | Pinned version | Used by |',
    '|------|----------------|---------|',
    `| emsdk (Emscripten) | \`${pins.emsdk}\` | \`npm run wasm:build\`, \`build-wasm.yml\`; part of \`sim_core_source_hash()\`, so a binary built before a bump reads as stale |`,
    `| naga-cli | \`${pins.naga}\` | \`npm run check:wgsl\` (the Firefox / wgpu proxy) |`,
    `| Node | \`${pins.node}\` | every workflow (\`.nvmrc\`) |`,
    `| Playwright | \`${pins.playwright}\` | \`npm run test:e2e*\`; fixes the Chromium build the image baselines are rendered with |`,
    END
  ].join('\n');
}

function mirrors(pins) {
  const readme = readFileSync(join(ROOT, README), 'utf8');
  const a = readme.indexOf(BEGIN);
  const b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${README}: toolchain markers missing`);
  return {
    '.nvmrc': `${pins.node}\n`,
    [README]: readme.slice(0, a) + readmeTable(pins) + readme.slice(b + END.length)
  };
}

// ── check:toolchain ────────────────────────────────────────────────────────
/**
 * A version literal next to its tool's name, anywhere but the pin file. Each
 * pattern captures the version; a hit is a hard-coded copy.
 */
const HARD_CODED = [
  { tool: 'emsdk', re: /\bemsdk\b[^\n]{0,40}?\b(\d+\.\d+\.\d+)\b/gi },
  { tool: 'emsdk', re: /\bemscripten\b[^\n]{0,24}?\b(\d+\.\d+\.\d+)\b/gi },
  { tool: 'naga', re: /\bnaga(?:-cli)?\b[^\n]{0,40}?\b(\d+\.\d+\.\d+)\b/gi },
  { tool: 'playwright', re: /@playwright\/test\b[^\n]{0,20}?\b(\d+\.\d+\.\d+)\b/gi },
  { tool: 'node', re: /\bnode-version:\s*['"]?(\d+[\w.]*)/gi }
];

/**
 * Lines that name a version for a reason other than choosing what to install.
 * `file` is repo-relative; `match` must appear on the offending line.
 */
const ALLOWED = [
  // The mirrors, verified against the pin above.
  { file: 'package.json', match: '"@playwright/test"' },
  { file: README, match: '| emsdk (Emscripten) |' },
  { file: README, match: '| naga-cli |' },
  // Measurement records: which compiler produced a published number.
  { file: 'cpp/bench-baseline.json', match: '"flags"' },
  { file: README, match: 'Compile-flag study' },
];

const SCAN = /\.(md|mjs|js|ts|json|ya?ml|sh|txt|flags)$|(^|\/)Makefile$/;
const SKIP = /^(node_modules|dist|build|cpp\/build|tools\/lint\/node_modules|test-results|\.git)\/|package-lock\.json$|^config\/toolchain\.json$|^scripts\/toolchain\.mjs$|^scripts\/tests\/toolchain\.test\.mjs$/;

/** Hard-coded tool versions in `files` (`{ path: text }`). Pure — test:toolchain feeds it fixtures. */
export function findHardCoded(files, allowed = ALLOWED) {
  const hits = [];
  for (const [file, text] of Object.entries(files)) {
    const lines = text.split('\n');
    for (const { tool, re } of HARD_CODED) {
      for (const m of text.matchAll(re)) {
        const lineNo = text.slice(0, m.index).split('\n').length;
        const line = lines[lineNo - 1];
        if (allowed.some((a) => a.file === file && line.includes(a.match))) continue;
        hits.push({ file, line: lineNo, tool, version: m[1], text: line.trim() });
      }
    }
  }
  return hits;
}

function trackedFiles() {
  const out = execFileSync('git', ['ls-files', '-co', '--exclude-standard'], { cwd: ROOT, encoding: 'utf8' });
  return out.split('\n').filter((f) => f && SCAN.test(f) && !SKIP.test(f));
}

function check(pins) {
  const problems = [];
  for (const [file, want] of Object.entries(mirrors(pins))) {
    if (readFileSync(join(ROOT, file), 'utf8') !== want) problems.push(`${file} is stale — run npm run codegen:toolchain`);
  }
  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const dep = pkg.devDependencies?.['@playwright/test'];
  if (dep !== pins.playwright) problems.push(`package.json devDependencies["@playwright/test"] is "${dep}", pin is "${pins.playwright}" (exact, no range)`);
  const lock = JSON.parse(readFileSync(join(ROOT, 'package-lock.json'), 'utf8'));
  const locked = lock.packages?.['node_modules/@playwright/test']?.version;
  if (locked !== pins.playwright) problems.push(`package-lock.json resolves @playwright/test ${locked}, pin is ${pins.playwright} — npm install`);
  const engines = pkg.engines?.node ?? '';
  const floor = Number(/(\d+)/.exec(engines)?.[1]);
  if (!(floor <= Number.parseInt(pins.node, 10))) problems.push(`package.json engines.node "${engines}" excludes the pinned Node ${pins.node}`);

  const files = {};
  for (const f of trackedFiles()) {
    try { files[f] = readFileSync(join(ROOT, f), 'utf8'); } catch { /* deleted in the work tree */ }
  }
  for (const h of findHardCoded(files)) {
    problems.push(`${h.file}:${h.line} hard-codes ${h.tool} ${h.version} — read it from ${PIN_FILE} (node scripts/toolchain.mjs ${h.tool})\n      ${h.text}`);
  }
  return { problems, scanned: Object.keys(files).length };
}

// ── CLI ────────────────────────────────────────────────────────────────────
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const arg = process.argv[2];
  const pins = toolchain();
  if (arg === '--github-output') {
    const lines = `${TOOLS.map((t) => `${t}=${pins[t]}`).join('\n')}\n`;
    if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, lines);
    process.stdout.write(lines);
  } else if (arg === '--write') {
    for (const [file, text] of Object.entries(mirrors(pins))) {
      if (readFileSync(join(ROOT, file), 'utf8') !== text) {
        writeFileSync(join(ROOT, file), text);
        console.log(`[toolchain] wrote ${file}`);
      }
    }
  } else if (arg === '--check') {
    const { problems, scanned } = check(pins);
    for (const p of problems) console.error(`  FAIL: ${p}`);
    if (problems.length) {
      console.error(`[toolchain] ${problems.length} problem(s)`);
      process.exit(1);
    }
    console.log(`[toolchain] OK — ${TOOLS.map((t) => `${t} ${pins[t]}`).join(', ')}; ${scanned} files scanned, no hard-coded copy`);
  } else if (TOOLS.includes(arg)) {
    process.stdout.write(`${pins[arg]}\n`);
  } else {
    console.error(`usage: toolchain.mjs <${TOOLS.join('|')}> | --github-output | --write | --check`);
    process.exit(2);
  }
}
