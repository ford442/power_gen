/**
 * vite-plugin-precache.mjs — writes `dist/sw.js` for offline classroom boots
 * (#224 §5, docs/CLASSROOM.md).
 *
 * Hand-rolled rather than vite-plugin-pwa (Workbox): the whole job is "list
 * what the build wrote, hash it, fill in a 70-line worker", and that is
 * smaller than the dependency's config surface.
 *
 * After Vite has written the bundle *and* copied `src/public/` (wasm/sim_core.*,
 * the GLBs, icons, manifest), the plugin walks the out dir, so the precache list
 * is exactly what a deploy serves — no glob to keep in sync with the build. The
 * cache version is a hash over every URL *and its bytes*: `wasm/sim_core.wasm`
 * and the GLBs keep their names across releases, so names alone would miss a
 * rebuilt plant.
 *
 * `buildPrecacheList` / `renderServiceWorker` are pure and checked by
 * `npm run test:classroom`.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const SW_FILE = 'sw.js';
const TEMPLATE = fileURLToPath(new URL('../src/classroom/sw-template.js', import.meta.url));

/** Things the build writes that the app never fetches: the worker itself, maps, dotfiles, notes. */
const SKIP = [/^sw\.js$/, /\.map$/, /(^|\/)\./, /\.md$/i];

/** True when an out-dir-relative URL belongs in the precache. */
export function isPrecacheable(url) {
  return !SKIP.some((re) => re.test(url));
}

const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');

/**
 * @param {{ path: string, bytes: Uint8Array | string }[]} files
 *   Out-dir-relative paths (either separator) with their contents.
 * @returns {{ urls: string[], version: string }} Sorted, de-duplicated URLs and
 *   a 16-hex-digit version that changes when any URL or any byte does.
 */
export function buildPrecacheList(files) {
  const digests = new Map();
  for (const { path, bytes } of files) {
    const url = path.replace(/\\/g, '/').replace(/^(\.\/|\/)+/, '');
    if (url && isPrecacheable(url)) digests.set(url, sha256(bytes));
  }
  const urls = [...digests.keys()].sort();
  const version = createHash('sha256');
  for (const url of urls) version.update(`${url}\0${digests.get(url)}\n`);
  return { urls, version: version.digest('hex').slice(0, 16) };
}

/** Fill the worker template's two placeholders. */
export function renderServiceWorker({ urls, version }, template = readFileSync(TEMPLATE, 'utf8')) {
  if (!template.includes("'__PRECACHE_VERSION__'") || !template.includes('__PRECACHE_URLS__;')) {
    throw new Error('[precache] sw-template.js lost its placeholders');
  }
  return '// Generated by scripts/vite-plugin-precache.mjs — edit src/classroom/sw-template.js.\n' + template
    .replace("'__PRECACHE_VERSION__'", JSON.stringify(version))
    .replace('__PRECACHE_URLS__;', `${JSON.stringify(urls, null, 2)};`);
}

/** Every file under `dir`, as `{ path, bytes }` relative to it. */
function listFiles(dir, root = dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory()
      ? listFiles(full, root)
      : [{ path: relative(root, full), bytes: readFileSync(full) }];
  });
}

/** @returns {import('vite').Plugin} */
export default function precachePlugin() {
  let outDir = '';
  let logger = console;
  return {
    name: 'seg-precache',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
      logger = config.logger;
    },
    writeBundle: {
      sequential: true,
      order: 'post',
      handler() {
        const files = listFiles(outDir);
        const list = buildPrecacheList(files);
        writeFileSync(join(outDir, SW_FILE), renderServiceWorker(list));
        const cached = new Set(list.urls);
        const kB = files
          .filter((f) => cached.has(f.path.replace(/\\/g, '/')))
          .reduce((n, f) => n + f.bytes.length, 0) / 1024;
        logger.info(`[precache] ${SW_FILE}: ${list.urls.length} URLs, ${kB.toFixed(0)} kB, cache ${list.version}`);
      }
    }
  };
}
